package com.redhat.devtools.intellij.quarkus.projectWizard;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonProperty;

@JsonIgnoreProperties(ignoreUnknown = true)
public class QuarkusCategoryRef {
    @JsonProperty("id")
    private String id;

    @JsonProperty("name")
    private String name;

    public QuarkusCategoryRef() {
    }

    @JsonCreator(mode = JsonCreator.Mode.DELEGATING)
    public QuarkusCategoryRef(String name) {
        this.id = name != null ? name.toLowerCase() : null;
        this.name = name;
    }

    public QuarkusCategoryRef(String id, String name) {
        this.id = id;
        this.name = name;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    @Override
    public String toString() {
        return name != null ? name : id;
    }
}
